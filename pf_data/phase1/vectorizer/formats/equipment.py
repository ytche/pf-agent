def _dedup_adjacent_words(value: str) -> str:
    """相邻重复词合并（M5：AP 解渴高脚杯 `位置：无 无`、page_xxx
    `无 无 无`——解析残留：段值内重复词只可能是残留，去重保序）"""
    parts = value.split()
    if len(parts) > 1:
        dedup = [p for i, p in enumerate(parts)
                 if i == 0 or p != parts[i - 1]]
        if len(dedup) != len(parts):
            return " ".join(dedup)
    return value
