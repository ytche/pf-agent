# ---- 行锚与剥除（须在 CR 归一后运行，行锚依赖换行结构）----

_RE_URL_LINE = re.compile(r"^\[https?://[^\]]*\]\(https?://[^)]*\)[^\n]*$", re.M)
_RE_TRANSLATOR_LINE = re.compile(r"^\*\*译者[:：][^\n]*$", re.M)
