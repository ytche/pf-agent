    def _inline_chain_sink(self, items: list, cur: dict, rest: str,
                           pending_source: str) -> bool:
        """行内多条目链循环切分（P&P 无位置奇物家族，seed_62 ③④）：
        rest 含 `…制造成本：700gp凶猛魔法灵药（Elixir of Vicious
        Magic）位置：无；价格：1750gp…` 链头 → 循环切分：
          链头前段（上一条目字段链尾 + 正文残段）_parse_b1_body 挂 cur；
          链头条目独立开条；rest 更新为链头条目正文残段继续。
        守卫：
          ①链头标题后须以词表标签+冒号开头（_bare_inline_chain）——
            正文句 `…它们就成了灵药（elixir）。` group3=`。` 拒绝；
          ②链头前段尾部须是字段值残尾（`gp/磅/级/数字/；`）——正文
            法术引用 `暴怒法术（Furious Spell）制造成本：`（pre 尾
            `制造奇物，` 非值尾）拒绝伪链头、继续向后找真链头
            （seed_62 ④ 实测：Furious Spell 是制造条件值里的法术名）。
        返回 True = 消化了 ≥1 条链（rest 已全部切分完）"""
        done = False
        pos = 0
        while True:
            m = (_RE_INLINE_BARE_TITLE_EN.search(rest, pos)
                 or _RE_INLINE_BARE_TITLE_TAIL.search(rest, pos))
            if not m:
                break
            g3 = rest[m.end():].strip()
            if not self._bare_inline_chain(g3):
                pos = m.end()
                continue
            pre = rest[:m.start()].rstrip()
            # 空 pre（链头在段首，_sink_inline_chain 已切行首段）放行；
            # 非空 pre 须以字段值残尾结尾（正文引用 `（Furious Spell）
            # 制造成本：` pre 尾 `制造奇物，` 非值尾 → 拒绝伪链头）
            if pre and not re.search(r"(?:gp|磅|级|[0-9]|[；;])$", pre, re.I):
                pos = m.end()
                continue
            if pre:
                pf, pt = self._parse_b1_body(pre, cur["title"])
                cur["fields"].update(pf)
                if pt:
                    cur["text"] += pt + "\n"
            # 链头条目：与 bm_bare/m_tail 分支同口径（_RE_ZH_BODY 切正文
            # 起点，字段链 _parse_b1_body 挂 fields、正文残体挂 text）
            mb = _RE_ZH_BODY.search(g3)
            if mb:
                chain_part = re.sub(r"[ \t]*\|[ |]*$", "",
                                    g3[:mb.start()].strip())
                rest = re.sub(r"[ \t]*\|[ |]*$", "",
                              g3[mb.start():].strip())
                pf, pt = self._parse_b1_body(chain_part, m.group(1))
            else:
                pf, pt = self._parse_b1_body(g3, m.group(1))
                rest = ""
            self._make_item(items, cur, m.group(1),
                            self._clean_en(m.group(2)), "", pending_source)
            cur = items[-1]
            cur["fields"].update(pf)
            if pt:
                cur["text"] += pt + "\n"
            done = True
            pos = 0
        # 无更多链头 → 剩余 rest（最后链头条目正文残段）挂 cur text
        if done and rest.strip():
            cur["text"] += rest.strip() + "\n"
        return done

    def _sink_inline_chain(self, items: list, cur: dict, line: str,
                           pending_source: str) -> bool:
        """无标题行行内条目链（GLUE 小节标记 + 条目，seed_62 ①）：
        `灵药 ELIXIRS在那些魔法商品…最强的那些。敏捷灵药（Elixir of
        Agility）位置：无；价格：450gp…`——行首段（小节过渡正文）挂
        当前条目 text（无条目开 intro），链头起 _inline_chain_sink
        循环切分。返回 True = 行已消化"""
        m = None
        for mm in (list(_RE_INLINE_BARE_TITLE_EN.finditer(line))
                   + list(_RE_INLINE_BARE_TITLE_TAIL.finditer(line))):
            if self._bare_inline_chain(line[mm.end():].strip()):
                m = mm
                break
        if m is None:
            return False
        pre = line[:m.start()].strip()
        if pre:
            if cur is not None:
                cur["text"] += pre + "\n"
            else:
                cur = self._open_item(items, "intro", text=pre + "\n")
        return self._inline_chain_sink(items, cur, line[m.start():],
                                       pending_source)

    def _bare_inline_chain(self, tail: str) -> bool:
        """裸行标题行内字段链检测（P&P 家族 `价格：65gp重量：-磅`——
        标题（EN）后无星壳字段同行；正文句不会以 `中文标签：` 开头，
        词表校验防正文误判）。标题后是空行/出处行的形态（seed_09
        焦油炸弹）由 _bare_title_follows 覆盖，此处只管行内证据"""
        if not tail:
            return False
        m = _RE_COLON_LEAD.match(tail.strip())
        return bool(m and m.group(1) in ALL_EQUIP_FIELD_LABELS)

    def _make_item(self, items: list, cur: dict, title_cn: str, title_en: str,
                   body: str, pending_source: str):
        r"""星壳标题开条目；正文紧跟闭壳（组3）并入 text。
        组3 剥首尾星（M3 收尾 B）：呼吸水晶 `）*****出自《…》***` 5 星共壳
        （标题闭壳 `****` + 出处行开壳 `*`）——FULL 闭壳 `\*{2,4}` 吃 4 星，
        组3 残留 `*出自《…》***`，剥星后出处行纯净落 text"""
        item = self._open_item(items, "item", title=title_cn.strip(),
                               title_en=self._clean_en(title_en))
        item["source"] = pending_source
        body = re.sub(r"^\*+|\*+$", "", body or "").strip()
        if body:
            item["text"] = body + "\n"

    def _value_unclosed(self, line: str) -> bool:
        """值行括号未闭合（seed_01 `敏捷伤害（如果…新的 DC 12` 跨行值段
        无 `；` 结尾但 `（` 未闭 → 值未完，继续吞下一行）"""
        return (line.count("（") + line.count("(")
                > line.count("）") + line.count(")"))

    def _assign_field_value(self, cur: dict, key: str, raw: str) -> str:
        """字段值归一：剥 `：` 前缀（字段分行形态值行 `：+1加值；`，
        seed_23）；`：— 正文` 同行分离（值=`—` 归字段、正文挂 text——
        重量 `：— 这个特殊能力仅能够加持…` 不得整行吞进字段值）；
        `这` 字正文守卫（与冒号字段行 _RE_ZH_BODY 同口径，seed_45
        十字军长剑 `灵光：中等塑能系 这把+1神圣…` 实测——正文整段
        吞进 aura 字段、text 空）"""
        # 跨行合并空白归一（`13,200  gp` 行尾空格断行残留，与 B1 值处
        # `re.sub(r"[ \t]{2,}", " ")` 同口径）
        raw = re.sub(r"[ \t]{2,}", " ", raw)
        m = _RE_COLON_VALUE.match(raw.strip())
        if m:
            raw = m.group(1).strip()
        # 正文守卫仅对规范字段生效（EXTRA 保真字段——效果/描述/豁免等——
        # 值天生长描述文本，含「这个/虽然」是正常内容：seed_01 效果值
        # `从这个毒素受到…` 实测误切；规范字段值短结构化，含正文词必然
        # 是正文粘连，须切）
        if key not in _CANONICAL_KEY_SET:
            return raw
        db = _RE_DASH_BODY.match(raw)
        if db:
            body = db.group(2).strip()
            if body:
                cur["text"] += body + "\n"
            return db.group(1)
        zh = _RE_ZH_BODY.search(raw)
        if zh:
            # 量词到行尾完整挂 text（仅挂量词会丢正文，seed_45 实测
            # `这把+1神圣破敌…` 只留「这把」）
            cur["text"] += raw[zh.start():].strip() + "\n"
            raw = raw[:zh.start()].strip()
        # 条目名前缀正文判定（空隙密封软膏实测：正文行以条目名开头
        # `空隙密封软膏存放于…`，无 `这*` 指示词——lines 过滤空行丢失
        # 空行终止符，正文被吞进字段值）：条目标题首 2 字为长行 → 整段
        # 挂 text（字段值续行不会以条目名前缀开头）。M3 收尾扩展「值前
        # 条目名」形态（值短 + 条目名在值后：哨兵种子 `0.5 磅 哨兵种子
        # 是…`、召唤者长袍 `5磅召唤者长袍是…`、潜伏者吹箭 `62302gp潜伏
        # 者吹箭用…`）——find 条目名位置，pre 段短（≤14 字符）且以值
        # 标记结尾（磅/gp/–）才切——箱子 `250磅（超大号箱子）` 括号
        # 注释多档链 pre 以「号」结尾不切（合法长值保真）
        if cur["title"] and len(raw) >= 20:
            probe = cur["title"][:2]
            if raw.startswith(probe):
                cur["text"] += raw.strip() + "\n"
                raw = ""
            else:
                pos = raw.find(probe)
                if (0 < pos <= 14
                        and raw[:pos].rstrip().endswith(("磅", "gp", "GP", "–", "-"))):
                    cur["text"] += raw[pos:].strip() + "\n"
                    raw = raw[:pos].strip()
        # M6 A-1 字段层剥壳（2026-08-09，白名单见 _FIELD_STRIP_TARGETS）：
        # item_name/EXTRA 不在白名单（B 类脚注星 + 正文斜体保真）
        if key in _FIELD_STRIP_TARGETS and "*" in raw:
            raw = _strip_field_stars(raw)
        return raw

