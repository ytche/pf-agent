_RE_INLINE_LINK = re.compile(r"\[[^\]]*\]\(https?://[^)]*\)")
def _strip_orphan_italic(text: str) -> str:
    """剥无配对斜体残迹星壳（KN160 家族）——行首/行尾单星。

    配对判据（seed_70 VC 蹦跳拖鞋）：`*蛛行术*` 这类成对斜体段（制造
    条件/要求值内法术名）若落行尾，旧行尾剥星规则会误剥闭壳星，破坏
    值匹配。判据：行内单星（非 `**`）总数——偶数 = 斜体段成对保留；
    奇数 = 存在无配对残迹星，剥行首/行尾裸星。
    """
    out = []
    for line in text.split("\n"):
        # 段首星壳对剥壳（M5 星壳 25 家族，KN160 缺口）：`*获得降灵：*` 这类
        # 行首成对斜体段（AP_装备 降灵条目）单星数为偶数，旧判据视为「成对
        # 保留」漏剥；段首星壳是源数据格式泄漏，剥壳保留内文（`*扼杀
        # （Choke）*：` → `扼杀（Choke）：`）。仅匹配行首，行中斜体段
        # （seed_70 `*蛛行术*` 制造要求值）不碰。行首容忍全角空格
        # （page_632 `　*勇气板片*` 神话板片行）。
        line = re.sub(r"^[ \t　]*\*(?!\*)([^*\n]+?)\*(?!\*)", r"\1", line)
        # 句读符后行尾裸星剥除（page_632 塔因盔）：`…变形。* ` 闭壳星前
        # 是句读符——斜体段内文不可能以句读符结尾再接星，此形态必为
        # 源数据格式残迹，无条件剥。修复「孤星恰凑偶数 → 判据误判成对
        # 保留」盲区（`*动物型态IV[/u]` 开壳 1 + `变形。* ` 闭壳 1 = 2
        # 偶数）。seed_70 `*蛛行术*` 行尾闭壳星前是汉字名非句读，不中。
        line = re.sub(r"([。．！？：；])\*[ \t　]*$", r"\1", line)
        # BBCode 残迹（page_632 `*动物型态IV[/u]`、PotR_奇物 130
        # `巧言术（tongues）[/size]`）：开标记/闭标记顶替斜体闭壳星或
        # 无配对泄漏（全库扫描仅 `[/u]`/`[/size]` 2 家族），剥开壳星保留
        # 内文 + 清残迹
        line = re.sub(r"\*([^*\n]+?)\[/[a-z]+\]", r"\1", line)
        line = re.sub(r"\[/?[a-z]+\]", "", line)
        singles = re.findall(r"(?<!\*)\*(?!\*)", line)
        if len(singles) % 2 == 1:
            line = re.sub(r"^[ \t　]*\*(?!\*)", "", line)
            line = re.sub(r"(?<!\*)\*[ \t　]*$", "", line)
        out.append(line)
    return "\n".join(out)


# ---- A-2 星壳粘连/空壳/三连星清理（M6 方案 A，2026-08-09）----
# 形态家族（产物全库 dry-run 定稿，5386 chunks 零边界影响）：
#   R1b 来源行链接残渣 `** *****出自《…》***`（ISI 醉蜂赐/胡蜂腑，链接壳
#       `[x](url)` 被 _RE_INLINE_LINK 剥除后行首暴露星——本函数必须在其后）
#   R1a 三连星对 `***锋锐术***`（黑市诅咒遗物法术强调/page_775 特性标题/
#       HotD 来源行——3 星对是 HTML `<B>` 泄漏，剥成标准粗体保语义）
#   R3a/R3b 空壳行 `**` / `** **`（`<B></B>` 转换残渣，全库 484 行剥除）
#   R2b 粘连+空格开壳 `**A**** ****B`（格拉里昂武器特性/炼金功能材料）
#   R2a 粗体闭壳+开壳粘连 `**A****B**` → `**A** **B**`（4 星连续两侧均为
#       粗体内容字符）
#   R4b 6 星连续 `******` → `**`（C 形态标题尾壳，page_206~222 家族）
# 顺序约束：R2b 先于 R2a（`**A**** ****B` 的双 4 星若 R2a 先拆会二次拆乱）；
#   R1b 先于 R1a（来源行 `** *****出自…***` 若 R1a 先剥会从 5 星中部开剥
#   留 `** **` 残渣）
# ⚠️ R4a（`（****X****）` → `（X）`）已移除（2026-08-09）：dry-run 判「76 处
# 全合法可剥」系误判——全库命中全部是 ISG/ISC 切分器依赖结构（`_RE_ISG_TITLE`
# 的 `（?\*\*\*\*` 形态：ISC 章节标题 `**中文（****English****）****…` 与无前缀
# 条目头 `中文（****EN****）****字段…`），剥壳后 category/条目识别断裂（seed_19/
# 20/25/49 等回归）。「正文内真嵌套壳」与 `（****X****；Y）` 边缘形态一并登记
# KN189，不动切分器依赖形态。

# R1b/R1a 内容类 `[^*]`（非 `[^*\n]`）：源数据来源行/边栏标题常被 HTML
# 转换断行（`** *****出自《内海诡道  Inner Sea Intrigue \n50页》***`、
# `***边栏：芥子气（Mustard \nGas）***`，page_775），切分器 join 在剥壳
# 之后才拼成完整行——剥壳必须前向兼容断行形态（中间换行保留，join 归一）
_RE_SRC_LINE_STAR_RESIDUE = re.compile(
    r"^[ \t]*\*{1,4}[ \t]+\*{2,5}([^*]+?)\*{3}(?!\*)[ \t]*$", re.M)
_RE_TRIPLE_STAR_PAIR = re.compile(
    r"(?<!\*)\*{3}(?!\*)([^*]+?)(?<!\*)\*{3}(?!\*)")
# R3a 尾随空白版：`**` / `**　 ` / `** `（2 星 + 全角/半角空格残渣，
# page_211 交通工具页实测 `**　 ` 家族；R3b 专剥 `** **` 成对形态）
_RE_EMPTY_STAR_LINE = re.compile(r"^\*\*[ \t　]*$", re.M)
_RE_EMPTY_STARPAIR_LINE = re.compile(r"^\*\*[ \t　]*\*\*$", re.M)
_RE_GLUE_SPACE_OPEN = re.compile(
    r"(?<!\*)\*\*(?!\*)([^*\n（(]+?)\*\*\*\*(?!\*)[ \t]+\*\*")
# 4 星连续两侧字符集：非星、非括号（全/半角）——括号两侧为嵌套形态归 R4a
# 粘连拆壳判据：4 星连续 = 粗体闭壳+开壳。仅在「前后都是粗体内容字符」时
# 才是真粘连（`**A****B**` 无空格渲染粘连）；后跟空格/行尾/标点是合法紧邻
# 粗体（ISG/ISC 标题 `**魔法武器**** Magic Weapons****`、`**A**** B**`）。
# 排除集含全角 `．，：` 与半角 `-`：`****．****`/`****-****` 是 _RE_ISG_TITLE
# 组1 依赖连接符形态（seed_18 凯登/宗-库山神坛，L760 注释），`****，****`
# 由 L761 专门归一；`**标签：****` 是章节头「标签+冒号+四星闭壳」依赖形态
# （seed_20，`**魔法物品：****`）——冒号属闭壳粗体内容尾，非开壳，R2a 让路。
_RE_STAR_CONTENT_CHAR = r"[^*\n\s（(【）)\]）．，：-]"
_RE_GLUE_4STAR = re.compile(
    rf"(?<={_RE_STAR_CONTENT_CHAR})\*{{4}}(?={_RE_STAR_CONTENT_CHAR})")
_RE_SIX_PLUS_STAR = re.compile(r"\*{6,}")


def _strip_star_glue_artifacts(text: str) -> str:
    """A-2：星壳粘连/空壳行/三连星对/嵌套括号/6 星尾壳清理。

    调用点：_normalize_custom 中 _RE_INLINE_LINK 剥除之后（R1b 行首锚定
    依赖链接壳已剥除）。行级 _strip_orphan_italic 在前（单星残迹），本
    函数处理多星家族——三连星开壳 `***` 首星后是星，前者不碰。
    """
    text = _RE_SRC_LINE_STAR_RESIDUE.sub(r"\1", text)   # R1b
    text = _RE_TRIPLE_STAR_PAIR.sub(r"**\1**", text)    # R1a
    text = _RE_EMPTY_STAR_LINE.sub("", text)            # R3a
    text = _RE_EMPTY_STARPAIR_LINE.sub("", text)        # R3b
    text = _RE_GLUE_SPACE_OPEN.sub(r"**\1**", text)     # R2b
    text = _RE_GLUE_4STAR.sub("** **", text)            # R2a
    text = _RE_SIX_PLUS_STAR.sub("**", text)            # R4b
    return text


